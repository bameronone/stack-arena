// Measures how much one extra copy of each card improves real mid-game builds.
// Builds come from snapshots of bot matches; each card is added to builds that
// could legally buy it, then fought against other snapshots with paired seeds.
// Writes src/ai/cardValues.js, which the bot uses as its base card value.
//   node tools/cardvalue.mjs [samplesPerCard=160]
import { writeFileSync } from 'node:fs';
import { createMatch, pairings, makeFight, resolveFight, finishRound, loadout } from '../src/engine/match.js';
import { botBan, botPick, botShop, botSignature, LEVELS } from '../src/ai/bot.js';
import { CARDS } from '../src/data/cards.js';
import { CHAR_BY_ID } from '../src/data/characters.js';
import { isBanned, cardCost } from '../src/engine/shop.js';
import { Fight } from '../src/engine/combat.js';
import { makeRng } from '../src/rng.js';

const SAMPLES = Number(process.argv[2] || 160);
LEVELS.normal.noise = 3; // varied builds
const snaps = [];
for (let i = 0; snaps.length < 1500; i++) {
  const m = createMatch({ seed: 90000 + i * 13, players: [{ name: 'A', isBot: true }, { name: 'B', isBot: true }] });
  botBan(m, 0); botBan(m, 1); botPick(m, 0); botPick(m, 1);
  while (m.phase !== 'over' && m.round < 30) {
    if (m.phase === 'signature') { botSignature(m, 0); botSignature(m, 1); }
    botShop(m, 0); botShop(m, 1);
    if ([3, 5, 7, 9, 11].includes(m.round)) for (const p of m.players) snaps.push({ lo: loadout(p), bans: m.bans, round: m.round });
    for (const [a, b, g] of pairings(m)) resolveFight(m, a, b, makeFight(m, a, b).runToEnd(), g);
    finishRound(m);
  }
}
const rng = makeRng(7);
const score = (r) => (r.winner === 0 ? 1 + r.survivorHpPct : r.winner === 1 ? -1 - r.survivorHpPct : 0);
const values = {};
for (const card of CARDS) {
  let gain = 0, n = 0, gainFit = 0, nFit = 0;
  for (let tries = 0; n < SAMPLES && tries < SAMPLES * 20; tries++) {
    const s = rng.pick(snaps);
    if (isBanned(card, s.bans) || (s.lo.cards[card.id] || 0) >= card.max) continue;
    if (typeof card.tier === 'number' && card.tier >= 3 && s.round < 7) continue;
    const opp = rng.pick(snaps.filter((x) => x.round === s.round));
    const seed = rng.int(1e9);
    const plus = { ...s.lo, cards: { ...s.lo.cards, [card.id]: (s.lo.cards[card.id] || 0) + 1 } };
    let g = 0;
    for (let k = 0; k < 3; k++) g += score(new Fight(plus, opp.lo, seed + k).runToEnd()) - score(new Fight(s.lo, opp.lo, seed + k).runToEnd());
    g /= 3;
    gain += g; n++;
    const ch = CHAR_BY_ID[s.lo.charId];
    if (card.tags.some((t) => t === ch.trigger || ch.resources.includes(t))) { gainFit += g; nFit++; }
  }
  values[card.id] = {
    all: +(gain / Math.max(1, n)).toFixed(4),
    fit: nFit >= 15 ? +(gainFit / nFit).toFixed(4) : null,
    perGold: +((gain / Math.max(1, n)) / cardCost(card)).toFixed(4),
  };
}
const body = Object.entries(values).map(([id, v]) => `  ${id}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(new URL('../src/ai/cardValues.js', import.meta.url),
  `// Generated by tools/cardvalue.mjs. Average change in fight score (-2..+2)\n// from one extra copy: across all builds, and for gladiators that share a tag.\nexport const CARD_VALUES = {\n${body}\n};\n`);
const sorted = Object.entries(values).sort((a, b) => b[1].all - a[1].all);
console.log('top', sorted.slice(0, 12).map(([id, v]) => `${id} ${v.all}`).join(', '));
console.log('bottom', sorted.slice(-12).map(([id, v]) => `${id} ${v.all}`).join(', '));
