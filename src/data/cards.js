// Card definitions. Every card is data plus small hook functions the combat
// engine calls. `n` is always the number of copies the owner has.
//
// Hooks:  setup(u, n)                 adjust stats before the fight
//         onStart(f, u, n)            fight begins
//         onAttack(f, u, n)           every attack, even ones that get dodged
//         onHit(f, u, n, hit)         attack connected ({ crit, dmg })
//         onCrit(f, u, n, hit)
//         onEvade(f, u, n)            you dodged
//         onPain(f, u, n)             each time you lose another slice of max HP
//         onCast(f, u, n)
//         onFreeze(f, u, n)           you froze the enemy
//         onHitTaken(f, u, n, src)
//         onShieldBreak(f, u, n)
//         every: [seconds, (f, u, n) => {}]
//         bonusDamage(f, u, n)        flat damage added to each attack
//
// Generator cards (trigger + resource) always grant their stacks. Cards that
// make stacks on their own only have a 30% chance, so builds want a trigger.

